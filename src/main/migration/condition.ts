import type {MigrationCondition} from '../../shared/migration'
import {compileMysqlFilter,type BrowseFilter} from '../../shared/browse-filter'
import {quoteIdentifier} from '../operations/sql-policy'
import type {SqlValue} from '../../shared/types'

export function migrationBrowseFilter(condition:MigrationCondition):BrowseFilter{
 return {join:'and',groups:[{join:'and',rules:[{field:condition.field,operator:condition.operator,type:condition.type,value:condition.value}]}],sort:[]}
}
/** Use the existing bound-filter compiler. Never interpolate the value into
 * SQL, even on a source connection using NO_BACKSLASH_ESCAPES. */
export function sqlMigrationCondition(condition:MigrationCondition|undefined,fields:string[],dialect:'mysql'|'sqlite'):{where:string;parameters:SqlValue[]}{
 if(!condition)return {where:'',parameters:[]}
 if(!fields.includes(condition.field)||condition.type==='ObjectId')throw new Error('MIGRATION_CONDITION: 筛选字段或类型不受支持')
 // Use an unambiguous synthetic table prefix generated by the same compiler.
 const compiled=compileMysqlFilter('dbex_migration','source',migrationBrowseFilter(condition),dialect)
 const prefix='SELECT * FROM '+quoteIdentifier('dbex_migration')+'.'+quoteIdentifier('source')
 if(!compiled.sql.startsWith(prefix+' WHERE '))throw new Error('MIGRATION_CONDITION: 筛选字段或类型不受支持')
 return {where:compiled.sql.slice(prefix.length),parameters:compiled.parameters}
}
